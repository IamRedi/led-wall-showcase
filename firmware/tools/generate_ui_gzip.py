#!/usr/bin/env python3
"""Generate the DS4 build's compact, byte-identical V5 dashboard asset."""

import subprocess
from pathlib import Path

import zopfli.gzip


ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "src/api/ui_content.cpp").read_text()
start = source.index('R"lwui_v1(') + len('R"lwui_v1(')
end = source.index(')lwui_v1";', start)
html = source[start:end]
script_start = html.rfind("<script>") + len("<script>")
script_end = html.index("</script>", script_start)
if script_start < len("<script>"):
    raise ValueError("dashboard script not found")
minified = subprocess.run(
    ["terser", "--compress", "toplevel=true,passes=3", "--mangle", "toplevel=true"],
    input=html[script_start:script_end],
    text=True,
    capture_output=True,
    check=True,
).stdout
minified_html = subprocess.run(
    ["node", str(ROOT / "tools/minify_ui_html.cjs")],
    input=html[:script_start] + minified + html[script_end:],
    text=True,
    capture_output=True,
    check=True,
).stdout
payload = minified_html.encode("utf-8")
compressed = zopfli.gzip.compress(payload, numiterations=15)
rows = [compressed[i:i + 16] for i in range(0, len(compressed), 16)]
body = "\n".join("  " + ", ".join(f"0x{byte:02x}" for byte in row) + "," for row in rows)
target = ROOT / "src/api/ui_gzip.inc"
target.write_text(
    "// Generated by firmware/tools/generate_ui_gzip.py; do not edit.\n"
    "const unsigned char kIndexGzip[] LW_UI_PROGMEM = {\n"
    + body + "\n};\n"
)
print(f"UI {len(payload)} -> {len(compressed)} bytes")
